// Bash script that installs Docker and starts the test apps on a Linux VM:
// DVWA (80), Juice Shop (3000), WebGoat (8081), plus an nginx front door that adds
// TLS for DVWA (443) and Juice Shop (8443) and a standard-port HTTP alias for Juice Shop (8080).
// Array of strings (not a template literal) so bash ${ } never clashes with JS.
const { IMAGES, TEST_APP_PORTS } = require('../lib/testApps');
function generateTestAppsScript() {
  return [
    '#!/bin/bash',
    'set -euo pipefail',
    'trap \'echo "SCRIPT FAILED at line $LINENO"\' ERR',
    '',
    'echo "=== Step 0: Checking internet access ==="',
    'can_resolve() { getent hosts registry-1.docker.io >/dev/null 2>&1; }',
    'if ! can_resolve; then',
    '  echo "DNS lookups are failing. Waiting 30s in case the network is still coming up..."',
    '  sleep 30',
    'fi',
    'if ! can_resolve; then',
    '  echo "Still failing. Trying public DNS servers (8.8.8.8, 1.1.1.1)..."',
    '  cp /etc/resolv.conf /etc/resolv.conf.zpa-backup 2>/dev/null || true',
    '  rm -f /etc/resolv.conf',
    '  printf "nameserver 8.8.8.8\\nnameserver 1.1.1.1\\n" > /etc/resolv.conf',
    'fi',
    'if ! can_resolve; then',
    '  [ -f /etc/resolv.conf.zpa-backup ] && cp /etc/resolv.conf.zpa-backup /etc/resolv.conf',
    '  echo "NO INTERNET: this VM cannot reach the internet (DNS and public DNS both fail)."',
    '  echo "Check the VM has internet access in CloudShare (environment network settings),"',
    '  echo "or pick a template whose VMs do. Docker and the app images must be downloaded."',
    '  false',
    'fi',
    'echo "Internet access OK"',
    '',
    'echo "=== Step 1: Installing Docker ==="',
    'if ! command -v docker >/dev/null 2>&1; then',
    '  if command -v apt-get >/dev/null 2>&1; then',
    '    export DEBIAN_FRONTEND=noninteractive',
    '    apt-get update -y',
    '    apt-get install -y docker.io curl',
    '  elif command -v dnf >/dev/null 2>&1; then',
    '    dnf install -y yum-utils',
    '    yum-config-manager --add-repo https://download.docker.com/linux/centos/docker-ce.repo',
    '    dnf install -y docker-ce docker-ce-cli containerd.io',
    '  else',
    '    echo "Unsupported OS: need apt-get or dnf to install Docker"',
    '    false',
    '  fi',
    'else',
    '  echo "Docker already installed"',
    'fi',
    'systemctl enable --now docker',
    '',
    'echo "=== Step 2: Starting DVWA on port 80 ==="',
    'docker rm -f dvwa >/dev/null 2>&1 || true',
    `docker run -d --restart unless-stopped --name dvwa -p 80:80 ${IMAGES.dvwa}`,
    '',
    'echo "=== Step 3: Starting Juice Shop on port 3000 ==="',
    'docker rm -f juiceshop >/dev/null 2>&1 || true',
    `docker run -d --restart unless-stopped --name juiceshop -p 3000:3000 ${IMAGES.juice}`,
    '',
    'echo "=== Step 4: Starting WebGoat on port 8081 ==="',
    'docker rm -f webgoat >/dev/null 2>&1 || true',
    `docker run -d --restart unless-stopped --name webgoat -p 8081:8080 -p 9090:9090 -e WEBGOAT_HOST=0.0.0.0 ${IMAGES.webgoat} || echo "(WebGoat failed to start - continuing without it)"`,
    '',
    'echo "=== Step 4b: Old mainstream servers: Apache httpd 2.4.49 (8082), Tomcat 8.5 (8083), WordPress 4.9 (8084) ==="',
    'docker rm -f httpd249 tomcat85 wordpress49 wpdb >/dev/null 2>&1 || true',
    `docker run -d --restart unless-stopped --name httpd249 -p 8082:80 ${IMAGES.httpd}`,
    `docker run -d --restart unless-stopped --name tomcat85 -p 8083:8080 ${IMAGES.tomcat}`,
    'docker network create zpa-wp >/dev/null 2>&1 || true',
    `docker run -d --restart unless-stopped --name wpdb --network zpa-wp -e MYSQL_ROOT_PASSWORD=zpa-shield -e MYSQL_DATABASE=wordpress -e MYSQL_USER=wordpress -e MYSQL_PASSWORD=wordpress ${IMAGES.mysql}`,
    `docker run -d --restart unless-stopped --name wordpress49 --network zpa-wp -p 8084:80 -e WORDPRESS_DB_HOST=wpdb -e WORDPRESS_DB_USER=wordpress -e WORDPRESS_DB_PASSWORD=wordpress -e WORDPRESS_DB_NAME=wordpress ${IMAGES.wordpress}`,
    '# Finish the WordPress installer non-interactively so the site (not the setup page) is what gets scanned',
    '(for i in $(seq 1 30); do sleep 5; curl -s -o /dev/null -m 5 http://localhost:8084/wp-admin/install.php && break; done;',
    ' curl -s -o /dev/null -m 20 -X POST "http://localhost:8084/wp-admin/install.php?step=2" --data-urlencode "weblog_title=ZPA Shield Test Blog" --data-urlencode "user_name=admin" --data-urlencode "admin_password=zpa-shield-demo" --data-urlencode "admin_password2=zpa-shield-demo" --data-urlencode "pw_weak=on" --data-urlencode "admin_email=admin@example.com" --data-urlencode "Submit=Install" || true) &',
    '',
    'echo "=== Step 5: TLS front door (nginx): 443 -> DVWA, 8443 -> Juice Shop, 8080 -> Juice Shop plain ==="',
    'mkdir -p /opt/zpa-shield/nginx/certs',
    'if [ ! -f /opt/zpa-shield/nginx/certs/server.crt ]; then',
    '  openssl req -x509 -nodes -newkey rsa:2048 -days 825 -subj "/CN=$(hostname -f 2>/dev/null || hostname)/O=ZPA Shield Test Apps" \\',
    '    -keyout /opt/zpa-shield/nginx/certs/server.key -out /opt/zpa-shield/nginx/certs/server.crt >/dev/null 2>&1',
    'fi',
    'cat > /opt/zpa-shield/nginx/nginx.conf <<\'NGINX\'',
    'events {}',
    'http {',
    '  ssl_certificate     /etc/nginx/certs/server.crt;',
    '  ssl_certificate_key /etc/nginx/certs/server.key;',
    '  ssl_protocols TLSv1 TLSv1.1 TLSv1.2;',
    '  server { listen 443 ssl;  location / { proxy_pass http://127.0.0.1:80;   proxy_set_header Host $host; } }',
    '  server { listen 8443 ssl; location / { proxy_pass http://127.0.0.1:3000; proxy_set_header Host $host; } }',
    '  server { listen 8080;     location / { proxy_pass http://127.0.0.1:3000; proxy_set_header Host $host; } }',
    '}',
    'NGINX',
    'docker rm -f zpa-front >/dev/null 2>&1 || true',
    `docker run -d --restart unless-stopped --name zpa-front --network host -v /opt/zpa-shield/nginx/nginx.conf:/etc/nginx/nginx.conf:ro -v /opt/zpa-shield/nginx/certs:/etc/nginx/certs:ro ${IMAGES.nginx}`,
    '',
    'echo "=== Step 6: Checking the apps answer ==="',
    'sleep 25',
    `for PORT in ${TEST_APP_PORTS.join(' ')}; do`,
    '  case $PORT in 443|8443) SCHEME=https;; *) SCHEME=http;; esac',
    '  CODE=$(curl -sk -o /dev/null -m 10 -w "%{http_code}" "$SCHEME://localhost:$PORT/" || true)',
    '  echo "port $PORT ($SCHEME) -> HTTP ${CODE:-no answer}"',
    'done',
    'docker ps --format "{{.Names}}: {{.Status}}"',
    'echo "VM_IPS: $(hostname -I)"',
    'echo "Test apps ready!"',
  ].join('\n')
}

module.exports = { generateTestAppsScript }
