// Bash script that installs Docker and starts the test apps on a Linux VM:
// DVWA (80), Juice Shop (3000), WebGoat (8081), plus an nginx front door that adds
// TLS for DVWA (443) and Juice Shop (8443) and a standard-port HTTP alias for Juice Shop (8080).
// Array of strings (not a template literal) so bash ${ } never clashes with JS.
const { IMAGES, IMAGE_FALLBACKS, TEST_APP_PORTS } = require('../lib/testApps');
const F = (k) => IMAGE_FALLBACKS[k].join(' ');
function generateTestAppsScript() {
  return [
    '#!/bin/bash',
    'set -euo pipefail',
    'trap \'echo "SCRIPT FAILED at line $LINENO" | tee -a /var/log/zpa-shield-status.log\' ERR',
    'exec > >(tee -a /var/log/zpa-shield-testapps.log) 2>&1',
    'mkdir -p /var/log; : > /var/log/zpa-shield-status.log',
    '',
    '# start_app NAME [docker run args...] -- IMAGE [fallback images...]',
    '# Tries each image in turn; a failure is logged, never fatal — one bad tag must not stop the other apps.',
    'start_app() {',
    '  local NAME=$1; shift; local ARGS=()',
    '  while [ "$1" != "--" ]; do ARGS+=("$1"); shift; done; shift',
    '  for IMG in "$@"; do',
    '    if docker image inspect "$IMG" >/dev/null 2>&1 || docker pull -q "$IMG" >/dev/null 2>&1; then',
    '      if docker run -d --restart unless-stopped --name "$NAME" "${ARGS[@]}" "$IMG" >/dev/null 2>&1; then echo "$NAME started from $IMG"; return 0; fi',
    '      echo "$NAME: docker run failed with $IMG: $(docker logs --tail 3 "$NAME" 2>&1 | tr \'\\n\' \' \')"; docker rm -f "$NAME" >/dev/null 2>&1 || true',
    '    else',
    '      echo "$NAME: image $IMG could not be pulled (tag missing or registry unreachable)"',
    '    fi',
    '  done',
    '  echo "WARNING: $NAME did not start from any of: $*" | tee -a /var/log/zpa-shield-status.log',
    '  return 0',
    '}',
    '',
    'echo "=== Step 0: Checking internet access ==="',
    'can_resolve() { getent hosts registry-1.docker.io >/dev/null 2>&1; }',
    'if ! can_resolve; then',
    '  echo "DNS lookups are failing. Waiting 30s in case the network is still coming up..."',
    '  sleep 30',
    'fi',
    'if ! can_resolve; then',
    '  echo "Still failing. Trying public DNS servers (8.8.8.8, 1.1.1.1)..."',
    '  cp /etc/resolv.conf /etc/resolv.conf.zpa-backup 2>/dev/null || true',
    '  rm -f /etc/resolv.conf',
    '  printf "nameserver 8.8.8.8\\nnameserver 1.1.1.1\\n" > /etc/resolv.conf',
    'fi',
    'if ! can_resolve; then',
    '  [ -f /etc/resolv.conf.zpa-backup ] && cp /etc/resolv.conf.zpa-backup /etc/resolv.conf',
    '  echo "NO INTERNET: this VM cannot reach the internet (DNS and public DNS both fail)."',
    '  echo "Check the VM has internet access in CloudShare (environment network settings),"',
    '  echo "or pick a template whose VMs do. Docker and the app images must be downloaded."',
    '  false',
    'fi',
    'echo "Internet access OK"',
    '',
    'echo "=== Step 1: Installing Docker ==="',
    'if ! command -v docker >/dev/null 2>&1; then',
    '  if command -v apt-get >/dev/null 2>&1; then',
    '    export DEBIAN_FRONTEND=noninteractive',
    '    apt-get update -y',
    '    apt-get install -y docker.io curl',
    '  elif command -v dnf >/dev/null 2>&1; then',
    '    dnf install -y yum-utils',
    '    yum-config-manager --add-repo https://download.docker.com/linux/centos/docker-ce.repo',
    '    dnf install -y docker-ce docker-ce-cli containerd.io',
    '  else',
    '    echo "Unsupported OS: need apt-get or dnf to install Docker"',
    '    false',
    '  fi',
    'else',
    '  echo "Docker already installed"',
    'fi',
    'systemctl enable --now docker',
    '',
    'echo "=== Step 2: Pulling all images in parallel ==="',
    `for IMG in ${Object.values(IMAGES).join(' ')}; do docker pull -q "$IMG" >/dev/null 2>&1 & done; wait`,
    'echo "Images pulled"',
    '',
    'echo "=== Step 3: Starting MySQL first (it initialises for 1-2 min) and every independent app ==="',
    'docker rm -f dvwa juiceshop webgoat httpd249 tomcat85 wpdb wordpress49 zpa-front >/dev/null 2>&1 || true',
    'docker network create zpa-wp >/dev/null 2>&1 || true',
    `start_app wpdb --network zpa-wp -e MYSQL_ROOT_PASSWORD=zpa-shield -e MYSQL_DATABASE=wordpress -e MYSQL_USER=wordpress -e MYSQL_PASSWORD=wordpress -- ${F('mysql')}`,
    `start_app dvwa -p 80:80 -- ${F('dvwa')}`,
    `start_app juiceshop -p 3000:3000 -- ${F('juice')}`,
    `start_app httpd249 -p 8082:80 -- ${F('httpd')}`,
    `start_app tomcat85 -p 8083:8080 -- ${F('tomcat')}`,
    `start_app webgoat -p 8081:8080 -p 9090:9090 -e WEBGOAT_HOST=0.0.0.0 -- ${F('webgoat')}`,
    '',
    'echo "=== Step 4: TLS front door (nginx): 443 -> DVWA, 8443 -> Juice Shop, 8080 -> Juice Shop plain ==="',
    'mkdir -p /opt/zpa-shield/nginx/certs',
    'if [ ! -f /opt/zpa-shield/nginx/certs/server.crt ]; then',
    '  openssl req -x509 -nodes -newkey rsa:2048 -days 825 -subj "/CN=$(hostname -f 2>/dev/null || hostname)/O=ZPA Shield Test Apps" \\',
    '    -keyout /opt/zpa-shield/nginx/certs/server.key -out /opt/zpa-shield/nginx/certs/server.crt >/dev/null 2>&1',
    'fi',
    'cat > /opt/zpa-shield/nginx/nginx.conf <<\'NGINX\'',
    'events {}',
    'http {',
    '  ssl_certificate     /etc/nginx/certs/server.crt;',
    '  ssl_certificate_key /etc/nginx/certs/server.key;',
    '  ssl_protocols TLSv1 TLSv1.1 TLSv1.2;',
    '  server { listen 443 ssl;  location / { proxy_pass http://127.0.0.1:80;   proxy_set_header Host $host; } }',
    '  server { listen 8443 ssl; location / { proxy_pass http://127.0.0.1:3000; proxy_set_header Host $host; } }',
    '  server { listen 8080;     location / { proxy_pass http://127.0.0.1:3000; proxy_set_header Host $host; } }',
    '}',
    'NGINX',
    `start_app zpa-front --network host -v /opt/zpa-shield/nginx/nginx.conf:/etc/nginx/nginx.conf:ro -v /opt/zpa-shield/nginx/certs:/etc/nginx/certs:ro -- ${F('nginx')}`,
    '',
    'echo "=== Step 5: Tomcat default apps + WordPress once MySQL is ready ==="',
    '# Old Tomcat images sometimes ship webapps.dist unpacked but no ROOT; make sure the default apps are served',
    '(sleep 8; docker exec tomcat85 sh -c \'[ -d webapps/ROOT ] || cp -r webapps.dist/. webapps/ 2>/dev/null || true\' >/dev/null 2>&1 || true) &',
    'for i in $(seq 1 40); do docker exec wpdb mysqladmin ping -uwordpress -pwordpress --silent >/dev/null 2>&1 && break; sleep 3; done',
    `start_app wordpress49 --network zpa-wp -p 8084:80 -e WORDPRESS_DB_HOST=wpdb -e WORDPRESS_DB_USER=wordpress -e WORDPRESS_DB_PASSWORD=wordpress -e WORDPRESS_DB_NAME=wordpress -- ${F('wordpress')}`,
    '# Finish the WordPress installer non-interactively (background; retries until the installer answers)',
    '(for i in $(seq 1 40); do sleep 5;',
    '   C=$(curl -s -o /dev/null -m 5 -w "%{http_code}" http://localhost:8084/wp-admin/install.php || true); [ "$C" = "200" ] || continue;',
    '   curl -s -o /dev/null -m 30 -X POST "http://localhost:8084/wp-admin/install.php?step=2" --data-urlencode "weblog_title=ZPA Shield Test Blog" --data-urlencode "user_name=admin" --data-urlencode "admin_password=zpa-shield-demo" --data-urlencode "admin_password2=zpa-shield-demo" --data-urlencode "pw_weak=on" --data-urlencode "admin_email=admin@example.com" --data-urlencode "Submit=Install";',
    '   curl -s -m 5 http://localhost:8084/ | grep -q "ZPA Shield Test Blog" && { echo "WordPress installed"; break; }; done) > /var/log/zpa-shield-wordpress.log 2>&1 &',
    '',
    'echo "=== Step 6: Waiting for the apps to answer (up to 2 min) ==="',
    `PORTS="${TEST_APP_PORTS.join(' ')}"`,
    'for i in $(seq 1 24); do',
    '  PENDING=""',
    '  for PORT in $PORTS; do case $PORT in 443|8443) SCHEME=https;; *) SCHEME=http;; esac; CODE=$(curl -sk -o /dev/null -m 4 -w "%{http_code}" "$SCHEME://localhost:$PORT/" || true); [ "$CODE" != "000" ] && [ -n "$CODE" ] || PENDING="$PENDING $PORT"; done',
    '  [ -z "$PENDING" ] && break; sleep 5',
    'done',
    'for PORT in $PORTS; do case $PORT in 443|8443) SCHEME=https;; *) SCHEME=http;; esac; CODE=$(curl -sk -o /dev/null -m 4 -w "%{http_code}" "$SCHEME://localhost:$PORT/" || true); echo "port $PORT ($SCHEME) -> HTTP ${CODE:-no answer}"; done',
    'echo "=== Containers ==="',
    'docker ps -a --format "{{.Names}}: {{.Status}}"',
    'for c in dvwa juiceshop webgoat httpd249 tomcat85 wpdb wordpress49 zpa-front; do S=$(docker inspect -f "{{.State.Status}}" $c 2>/dev/null || echo missing); [ "$S" = running ] || { echo "--- $c is $S; last log lines:"; docker logs --tail 15 $c 2>&1 | sed "s/^/    /"; }; done',
    'echo "VM_IPS: $(hostname -I)"',
    'echo "Test apps ready!"',
  ].join('\n')
}

module.exports = { generateTestAppsScript }
